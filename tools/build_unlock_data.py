"""Smithy list unlock data: romfs table/decoCreate.dcd and table/armorCreateA00..A04.acrd -> plugin/src/generated/unlock.rs

How the game decides what the smithy lists (MHGU 1.4.0 static analysis, docs/smithy-deco-unlock-analysis.md):
 - Decoration recipe: listed when the first mDispFlag materials (file order) have each been obtained at least once
   (the 'obtained item' bitset, indexed by game item number).
 - Armor recipe variant k (mNo[k]): listed when its made-before bit (recipe index * 4 + k) is set, or when the open
   condition mDispFlag passes and, if that condition asks for keys, every material with mKey == 2 has been obtained.

decoCreate.dcd:   f32 version, u32 count, count x 16 B: u16 mNo, u16 mDispFlag, 4 x (u16 mItem, u8 mNum)
armorCreateA0p:   f32 version, u32 count, count x 42 B: u16 mNo[4], u16 mDispFlag, 4 x (u16 mItem, u8 mNum, u8 mKey),
                  u16 mCategory, u16 mRank, 3 x (u16 mPiece, u16 mPieceNum)
Item numbers in these files are game item numbers (DB_Itm.Hex), armor numbers are series numbers per part
(mapped to DB armor ids with generated/armor_map.rs, made by tools/build_armor_map.py).
"""
import json
import re
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = ROOT / 'Database' / 'mhxx_all_tables.json'
TABLE = ROOT / 'UnpakingGU' / 'backup' / 'romfs' / 'nativeNX' / 'table'
GEN = Path(__file__).resolve().parents[1] / 'plugin' / 'src' / 'generated'


def main():
    db = json.loads(DB.read_text(encoding='utf-8'))
    game2db = {int(r['Hex'], 16): r['Itm_ID'] for r in db['DB_Itm']}
    jewel_items = {r['Itm_ID'] for r in db['DB_Jew']}
    amap = {}
    for p, s, a in re.findall(r'\((\d+),\s*(\d+),\s*(\d+)\)', (GEN / 'armor_map.rs').read_text(encoding='utf-8')):
        amap.setdefault((int(p), int(s)), int(a))

    # Decorations
    raw = (TABLE / 'decoCreate.dcd').read_bytes()
    _, count = struct.unpack_from('<fI', raw, 0)
    if len(raw) != 8 + count * 16:
        raise SystemExit('decoCreate.dcd 크기가 예상과 다름')
    deco = []
    for i in range(count):
        o = 8 + i * 16
        no, disp = struct.unpack_from('<HH', raw, o)
        mats = [struct.unpack_from('<HB', raw, o + 4 + k * 3) for k in range(4)]
        jewel = game2db.get(no)
        if jewel not in jewel_items:
            raise SystemExit(f'장식품 번호를 DB에서 찾지 못함: {no}')
        keys = [m for m, q in mats[:disp] if m and q]
        deco.append((jewel, keys))

    # Armor
    armor = []
    unmapped = 0
    for part in range(1, 6):
        raw = (TABLE / f'armorCreateA0{part - 1}.acrd').read_bytes()
        _, count = struct.unpack_from('<fI', raw, 0)
        if len(raw) != 8 + count * 42:
            raise SystemExit(f'armorCreateA0{part - 1}.acrd 크기가 예상과 다름')
        for i in range(count):
            o = 8 + i * 42
            nos = struct.unpack_from('<4H', raw, o)
            disp, = struct.unpack_from('<H', raw, o + 8)
            mats = [struct.unpack_from('<HBB', raw, o + 10 + k * 4) for k in range(4)]
            keys = [m for m, q, key in mats if m and q and key == 2]
            for k, no in enumerate(nos):
                if not no:
                    continue
                aid = amap.get((part, no))
                if aid is None:
                    # Two known cases: the second variant of Jaggi Faker / Jaggi X Faker (series 737, 779), which the
                    # DB does not list separately. Their first variant is mapped, so the DB armor is still covered.
                    unmapped += 1
                    continue
                armor.append((aid, part, i * 4 + k, disp, keys))
    armor.sort()
    if unmapped > 2:
        raise SystemExit(f'DB 방어구와 대응하지 않는 생산 레시피 변형 {unmapped}개 (예상 2개)')

    def keys(v):
        return '&[' + ', '.join(str(x) for x in v) + ']'

    lines = ['//! Generated by tools/build_unlock_data.py from the game tables decoCreate.dcd and armorCreateA0*.acrd. Do not edit.',
             '/// Decoration recipes: (decoration id = DB item id, key game item numbers that must have been obtained)',
             'pub static DECO_KEYS: &[(u16, &[u16])] = &[']
    lines += [f'    ({j}, {keys(k)}),' for j, k in deco]
    lines += ['];',
              '/// Armor recipe variants: (DB armor id, part 1-5, made-before bit = recipe index * 4 + variant,',
              '/// open condition (mDispFlag), key game item numbers (mKey == 2))',
              'pub static ARMOR_KEYS: &[(u16, u8, u16, u16, &[u16])] = &[']
    lines += [f'    ({a}, {p}, {bit}, {d}, {keys(k)}),' for a, p, bit, d, k in armor]
    lines.append('];')
    (GEN / 'unlock.rs').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'smithy unlock: decoration recipes {len(deco)}, armor recipe variants {len(armor)} '
          f'(armor {len({a for a, *_ in armor})})')


if __name__ == '__main__':
    main()
